    def frame(self, el, title):
        """An iframe. One framing a page on the web stays, its size in
        whole pixels, as HTML wants it, rounded as TextbookImprover's
        html-raw.lua rounds one, a half up ("371.4" is 371, "370.5" 371,
        "640px" 640). One framing a file of the repository's
        (Introduction to Python Programming's code runners, which the
        license of the code they run keeps out of the book) becomes a
        link to the page in the online book, for emit.py to make."""
        src = (el.get("src") or "").strip()
        if not re.match(r"^(https?:)?//", src):
            link = E("a", {"data-type": "local-interactive",
                           "data-src": src})
            link.text = title or "Interactive"
            self.note("local-interactive", f"{src}: a link to the online "
                      "book now")
            return link
        frame = E("iframe", {"src": self.book.url_href(self.module, src),
                             "title": title or None})
        for attr in ("width", "height"):
            value = (el.get(attr) or "").strip()
            pixels = re.match(r"^(\d+\.?\d*)\s*(px)?$", value)
            if pixels:
                # Not round(), which takes a half to the even number.
                value = str(math.floor(float(pixels.group(1)) + 0.5))
            if value:
                frame.set(attr, value)
        return frame

