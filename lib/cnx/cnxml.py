# Inline elements: what a paragraph may hold. Used to decide whether a
# child of a list item or a table cell starts a block.
INLINE = {"emphasis", "term", "link", "cite", "cite-title", "foreign",
          "sub", "sup", "newline", "space", "span", "footnote", "code",
          "quote", "math", "media", "label"}

NUMBER_STYLES = {"arabic": "1", "upper-alpha": "A", "lower-alpha": "a",
                 "upper-roman": "I", "lower-roman": "i"}

# Where code runs with the words around it, unless it says it's a block.
# OpenStax's assembly (nebuchadnezzar's cnxml-to-html5.xsl) takes code in
# a paragraph or a list so, and code anywhere else for a block; the rest
# here are lines of text too, which a block would break.
CODE_IN_TEXT = {"para", "list", "title", "caption", "term", "meaning",
                "label", "emphasis", "link", "foreign", "cite", "cite-title",
                "sub", "sup", "span"}
# An element of a block of code's, in its text while its lines are
# trimmed (a private-use character, which code doesn't hold).
CODE_MARK = ""


def embed_url(link):
    """The address a link embeds an exercise from ("#exercise/NAME" or
    "#ost/api/ex/TAG"), whether given as its url or its target-id; else
    None."""
    url = link.get("url") or ""
    target = link.get("target-id") or ""
    for prefix in ("#exercise/", "#ost/api/ex/"):
        if url.startswith(prefix):
            return url
        if target.startswith(prefix[1:]):
            return "#" + target
    return None


def list_mark(number, style):
    """An enumerated item's number in a list's number-style: 3, c, C,
    iii, or III."""
    if style in ("lower-alpha", "upper-alpha"):
        letters = ""
        while number > 0:
            number, rest = divmod(number - 1, 26)
            letters = chr(ord("a") + rest) + letters
        return letters.upper() if style == "upper-alpha" else letters
    if style in ("lower-roman", "upper-roman") and 0 < number < 4000:
        numerals = ""
        for value, letters in ((1000, "m"), (900, "cm"), (500, "d"),
                               (400, "cd"), (100, "c"), (90, "xc"),
                               (50, "l"), (40, "xl"), (10, "x"), (9, "ix"),
                               (5, "v"), (4, "iv"), (1, "i")):
            while number >= value:
                numerals += letters
                number -= value
        return numerals.upper() if style == "upper-roman" else numerals
    return str(number)


def code_lines(code):
    """A block of code's lines as its text's own. A newline element (a
    <br> by now) is a line break, and the line break the source writes
    after one isn't a second (Introduction to Python Programming writes
    both, and means one: a program's output, line by line). And the code
    loses the blank line it opens with, the indentation it closes with,
    and the indentation every line of it shares, which is the source's
    markup's, not the code's. What it holds (a program's example input,
    in bold) is a word of a line, kept."""
    for br in list(code.iter("br")):
        tail = br.tail or ""
        _put_text_before(br, "\n" + (tail[1:] if tail.startswith("\n")
                                     else tail))
        br.getparent().remove(br)
    children = list(code)
    texts = [code.text or ""] + [child.tail or "" for child in children]
    if any(CODE_MARK in text for text in texts):
        return
    lines = CODE_MARK.join(texts).split("\n")
    while lines and not lines[0].strip():
        lines.pop(0)
    parts = textwrap.dedent("\n".join(lines)).rstrip().split(CODE_MARK)
    code.text = parts[0] or None
    for child, tail in zip(children, parts[1:]):
        child.tail = tail or None


def code_breaks(code):
    """Each line of a block of code's own text ended by a <br>, its
    indentation kept as no-break spaces: code in a line of text, which
    a reader of HTML runs together but for its <br>s."""
    nodes = [code.text or ""]
    for child in code:
        nodes += [child, child.tail or ""]
        child.tail = None
    code.text = None
    for child in list(code):
        code.remove(child)
    for n, node in enumerate(nodes):
        if not isinstance(node, str):
            code.append(node)
            continue
        for i, line in enumerate(node.split("\n")):
            if i:
                code.append(E("br"))
            if i or not n:
                indent = len(line) - len(line.lstrip(" "))
                line = " " * indent + line[indent:]
            append_text(code, line)


def _put_text_before(element, text):
    """text where element stands, after what comes before it."""
    previous = element.getprevious()
    if previous is not None:
        previous.tail = (previous.tail or "") + text
    else:
        parent = element.getparent()
        parent.text = (parent.text or "") + text


def local(element):
    return etree.QName(element).localname


def ns(element):
    return etree.QName(element).namespace


def E(tag, attrib=None, text=None):
    el = etree.Element(tag)
    for k, v in (attrib or {}).items():
        if v is not None:
            el.set(k, v)
    if text:
        el.text = text
    return el


def append_text(parent, text):
    """Text at the end of parent: its text if it has no children, else
    the tail of its last child."""
    if not text:
        return
    if len(parent):
        last = parent[-1]
        last.tail = (last.tail or "") + text
    else:
        parent.text = (parent.text or "") + text


class Module:
    """A module's file, read: its id, title, abstract, class, and the
    tree. The title an outline gives it wins over its own."""

    def __init__(self, repo, module_id, title_override=None):
        self.id = module_id
        self.path = repo.module_path(module_id)
        self.dir = os.path.dirname(self.path)
        self.tree = parse(self.path)
        root = self.tree.getroot()
        self.root = root
        title = root.find(f"{{{CNXML}}}title")
        md = root.find(f"{{{CNXML}}}metadata")
        md_title = md.find(f"{{{MDML}}}title") if md is not None else None
        self.title_element = title if title is not None else md_title
        self.title_override = title_override
        self.uuid = ""
        self.abstract = None
        if md is not None:
            uuid = md.find(f"{{{MDML}}}uuid")
            self.uuid = (uuid.text or "").strip() if uuid is not None else ""
            abstract = md.find(f"{{{MDML}}}abstract")
            if abstract is not None and (len(abstract) or
                                         (abstract.text or "").strip()):
                self.abstract = abstract
        self.document_class = root.get("class", "")
        self.lang = root.get(XML_LANG, "")

    @property
    def title_text(self):
        if self.title_override:
            return self.title_override
        if self.title_element is None:
            return self.id
        return " ".join("".join(self.title_element.itertext()).split())


class Converter:
    """Converts one module. `book` answers questions about the rest of
    the book: whether a module is in it (for links), where a media file
    goes. `report` takes (where, check, detail)."""

    def __init__(self, module, book, report):
        self.module = module
        self.book = book
        self.report = report
        self.prefix = module.id + "__"
        self.unknown = {}

    # ids and links ---------------------------------------------------

    def id_of(self, value):
        return self.prefix + value if value else None

    def copy_id(self, src, dst):
        value = src.get("id")
        if value:
            dst.set("id", self.id_of(value))

    def note(self, check, detail):
        self.report(self.module.id, check, detail)

    # the page ---------------------------------------------------------

    def page(self):
        mod = self.module
        attrib = {"data-type": "page", "id": "page_" + mod.id,
                  "data-module": mod.id}
        if mod.uuid:
            attrib["data-uuid"] = mod.uuid
        if mod.document_class:
            attrib["class"] = mod.document_class
        if mod.lang:
            attrib["lang"] = mod.lang
        page = E("div", attrib)
        title = E("h1", {"data-type": "document-title"})
        if mod.title_override or mod.title_element is None:
            title.text = mod.title_text
        else:
            self.inline_children(mod.title_element, title)
        page.append(title)
        if mod.abstract is not None:
            abstract = E("div", {"data-type": "abstract"})
            self.children(mod.abstract, abstract)
            page.append(abstract)
        content = mod.root.find(f"{{{CNXML}}}content")
        if content is not None:
            if content.get("class"):
                page.set("data-content-class", content.get("class"))
            self.children(content, page)
        glossary = mod.root.find(f"{{{CNXML}}}glossary")
        if glossary is not None:
            page.append(self.glossary(glossary))
        for name, count in sorted(self.unknown.items()):
            self.note("unknown-element",
                      f"<{name}> x{count}, kept as a div or span of that class")
        return page

    # dispatch ---------------------------------------------------------

    def children(self, src, dst):
        """Convert src's content into dst, in order, text included."""
        append_text(dst, src.text)
        for child in src:
            if isinstance(child.tag, str):
                self.convert(child, dst)
            append_text(dst, child.tail)

    def inline_children(self, src, dst):
        self.children(src, dst)

    def formula(self, el):
        """A formula, its MathML unprefixed, its forced line breaks made
        rows (centered in an equation), and made presentation MathML
        where it's written in content MathML; a formula that can't be is
        reported."""
        math = mathml.copy(el)
        parent = el.getparent()
        mathml.lines_as_rows(math, center=el.get("display") == "block" or (
            parent is not None and local(parent) == "equation"))
        left = mathml.to_presentation(math)
        if left:
            text = " ".join("".join(math.itertext()).split())
            self.note("content-mathml", f"a formula in content MathML "
                      f"({left} isn't converted): {text[:80]}")
        return math

    def convert(self, el, dst):
        space = ns(el)
        name = local(el)
        if space == MATHML:
            dst.append(self.formula(el))
            return
        if space != CNXML:
            self.foreign_markup(el, dst)
            return
        handler = getattr(self, "do_" + name.replace("-", "_"), None)
        if handler is None:
            self.unknown[name] = self.unknown.get(name, 0) + 1
            tag = "span" if name in INLINE else "div"
            out = E(tag, {"class": "cnx-" + name})
            self.copy_id(el, out)
            self.children(el, out)
            dst.append(out)
            return
        handler(el, dst)

    def foreign_markup(self, el, dst):
        """QML, bibtexml, and anything else not CNXML or MathML: its
        text kept in a div, reported once per kind."""
        q = etree.QName(el)
        key = f"{{{q.namespace}}}{q.localname}"
        self.unknown[key] = self.unknown.get(key, 0) + 1
        out = E("div", {"class": "cnx-foreign " + q.localname})
        out.text = " ".join("".join(el.itertext()).split())
        dst.append(out)

    def lang(self, src, out):
        if src.get(XML_LANG):
            out.set("lang", src.get(XML_LANG))

    # structure --------------------------------------------------------

    def do_section(self, el, dst):
        depth = 1
        parent = el.getparent()
        while parent is not None and local(parent) == "section":
            depth += 1
            parent = parent.getparent()
        out = E("section", {"data-depth": str(depth),
                            "class": el.get("class")})
        self.copy_id(el, out)
        self.lang(el, out)
        if el.get("type"):
            out.set("data-element-type", el.get("type"))
        title = el.find(f"{{{CNXML}}}title")
        for child in el:
            if not isinstance(child.tag, str):
                append_text(out, child.tail)
                continue
            if child is title:
                # h3 for a page's top sections, h4 for theirs, as
                # OpenStax's assembly numbers them; emit.py sets the
                # levels the pages are written with.
                heading = E(f"h{depth + 2}", {"data-type": "title"})
                self.copy_id(child, heading)
                self.inline_children(child, heading)
                out.append(heading)
            else:
                self.convert(child, out)
            append_text(out, child.tail)
        dst.append(out)

    def titled_block(self, el, dst, data_type):
        """A note, an example, an exercise: a div whose title and label
        are kept for baking to place. The title is a div, as OpenStax's
        assembly makes it, so a recipe's selectors find what theirs do."""
        out = E("div", {"data-type": data_type, "class": el.get("class")})
        self.copy_id(el, out)
        self.lang(el, out)
        # A note can hold text as well as blocks: a reference written as
        # an inline note opens with its author's name (1,033 of them in
        # Principles of Management).
        append_text(out, el.text)
        for child in el:
            if not isinstance(child.tag, str):
                append_text(out, child.tail)
                continue
            name = local(child) if ns(child) == CNXML else None
            if name == "title":
                heading = E("div", {"data-type": "title"})
                self.copy_id(child, heading)
                self.inline_children(child, heading)
                out.append(heading)
            elif name == "label":
                out.set("data-label",
                        " ".join("".join(child.itertext()).split()))
            else:
                self.convert(child, out)
            append_text(out, child.tail)
        dst.append(out)
        return out

    def do_note(self, el, dst):
        out = self.titled_block(el, dst, "note")
        if el.get("type"):
            out.set("data-note-type", el.get("type"))
        if el.get("display"):
            out.set("data-display", el.get("display"))

    def do_example(self, el, dst):
        self.titled_block(el, dst, "example")

    def do_exercise(self, el, dst):
        links = el.findall(f".//{{{CNXML}}}link")
        if any(embed_url(link) for link in links):
            # An exercise kept in OpenStax's exercise bank: only its link
            # stays, with the exercise's id, as OpenStax's assembly keeps
            # it, for exercises.py to put the exercise in its place.
            if len(links) != 1:
                self.note("embedded-exercise-with-more",
                          f"{el.get('id')}: an embedded exercise holds "
                          f"{len(links)} links; its first is used")
            link = next(link for link in links if embed_url(link))
            self.do_link(link, dst)
            if el.get("id"):
                dst[-1].set("id", self.id_of(el.get("id")))
            return
        out = self.titled_block(el, dst, "exercise")
        if el.get("type"):
            out.set("data-element-type", el.get("type"))
        if el.get("print-placement"):
            out.set("data-print-placement", el.get("print-placement"))

    def do_problem(self, el, dst):
        self.titled_block(el, dst, "problem")

    def do_solution(self, el, dst):
        out = self.titled_block(el, dst, "solution")
        if el.get("type"):
            out.set("data-element-type", el.get("type"))
        if el.get("print-placement"):
            out.set("data-print-placement", el.get("print-placement"))

    def do_commentary(self, el, dst):
        self.titled_block(el, dst, "commentary")

    def do_rule(self, el, dst):
        out = self.titled_block(el, dst, "rule")
        if el.get("type"):
            out.set("data-element-type", el.get("type"))

    def do_statement(self, el, dst):
        self.titled_block(el, dst, "statement")

    def do_proof(self, el, dst):
        self.titled_block(el, dst, "proof")

    def do_definition(self, el, dst):
        """A definition in the content (in a glossary it's a dl entry)."""
        out = E("div", {"data-type": "definition", "class": el.get("class")})
        self.copy_id(el, out)
        dl = E("dl")
        for child in el:
            if not isinstance(child.tag, str):
                continue
            name = local(child)
            if name == "term":
                dt = E("dt")
                self.copy_id(child, dt)
                self.inline_children(child, dt)
                dl.append(dt)
            elif name == "meaning":
                dd = E("dd")
                self.copy_id(child, dd)
                self.children(child, dd)
                dl.append(dd)
            else:
                dd = E("dd", {"class": "cnx-" + name})
                self.children(child, dd)
                dl.append(dd)
        out.append(dl)
        dst.append(out)

    def glossary(self, el):
        out = E("div", {"data-type": "glossary"})
        for definition in el.findall(f"{{{CNXML}}}definition"):
            dl = E("dl")
            self.copy_id(definition, dl)
            for child in definition:
                if not isinstance(child.tag, str):
                    continue
                name = local(child)
                if name == "term":
                    dt = E("dt")
                    self.copy_id(child, dt)
                    self.inline_children(child, dt)
                    dl.append(dt)
                elif name == "meaning":
                    dd = E("dd")
                    self.copy_id(child, dd)
                    self.children(child, dd)
                    dl.append(dd)
                else:
                    dd = E("dd", {"class": "cnx-" + name})
                    self.children(child, dd)
                    dl.append(dd)
            out.append(dl)
        return out

    def do_div(self, el, dst):
        out = E("div", {"class": el.get("class")})
        self.copy_id(el, out)
        self.lang(el, out)
        self.children(el, out)
        dst.append(out)

    def do_para(self, el, dst):
        out = E("p", {"class": el.get("class")})
        self.copy_id(el, out)
        self.lang(el, out)
        title = el.find(f"{{{CNXML}}}title")
        append_text(out, el.text)
        for child in el:
            if not isinstance(child.tag, str):
                append_text(out, child.tail)
                continue
            if child is title:
                span = E("span", {"data-type": "title"})
                self.copy_id(child, span)
                self.inline_children(child, span)
                out.append(span)
            else:
                self.convert(child, out)
            append_text(out, child.tail)
        dst.append(out)

    def do_title(self, el, dst):
        """A title where none is expected (a list's, a table's, a
        figure's are taken by those handlers)."""
        out = E("span", {"data-type": "title"})
        self.copy_id(el, out)
        self.inline_children(el, out)
        dst.append(out)

    def do_label(self, el, dst):
        out = E("span", {"data-type": "label"})
        self.inline_children(el, out)
        dst.append(out)

    def do_quote(self, el, dst):
        block = el.get("display") == "block" or any(
            isinstance(c.tag, str) and local(c) in ("para", "list", "section",
                                                    "note", "table")
            for c in el)
        out = E("blockquote" if block else "q", {"class": el.get("class")})
        self.copy_id(el, out)
        self.lang(el, out)
        if el.get("url"):
            out.set("cite", el.get("url"))
        self.children(el, out)
        dst.append(out)

    def do_preformat(self, el, dst):
        out = E("pre", {"class": el.get("class")})
        self.copy_id(el, out)
        self.children(el, out)
        dst.append(out)

    def do_code(self, el, dst):
        """Code is a block where it says so, and where it stands as one:
        anywhere but in a line of text (a paragraph, a list, a title), as
        OpenStax's assembly reads it. Introduction to Python Programming
        and Principles of Data Science put their programs in notes and
        examples so, with no display="block". Code of class inline-code
        is inline anywhere, as OpenStax's stylesheet shows it (a table's
        cells hold it).

        A block of code that holds words in bold or italics (a program's
        run, its example input in bold, as Introduction to Python
        Programming shows one) is a paragraph of code, line by line,
        since a code block holds text alone."""
        display = el.get("display")
        block = display == "block" or (
            display != "inline"
            and "inline-code" not in (el.get("class") or "").split()
            and not any(ns(a) == CNXML and local(a) in CODE_IN_TEXT
                        for a in el.iterancestors()))
        code = E("code", {"class": el.get("class")})
        if el.get("lang"):
            code.set("data-lang", el.get("lang"))
        self.children(el, code)
        if not block:
            self.copy_id(el, code)
            dst.append(code)
            return
        code_lines(code)
        if code.xpath(".//strong | .//em | .//u"):
            code_breaks(code)
            out = E("p")
        else:
            classes = (el.get("class") or "").split()
            # Lines OpenStax numbers, which the text cites ("Line 6
            # shows…"), in the class Pandoc numbers them by.
            if "line-numbering" in classes:
                classes.append("numberLines")
            out = E("pre", {"class": " ".join(classes) or None})
        self.copy_id(el, out)
        out.append(code)
        dst.append(out)

    # lists ------------------------------------------------------------

    def do_list(self, el, dst):
        list_type = el.get("list-type", "bulleted")
        inline = el.get("display") == "inline"
        title = el.find(f"{{{CNXML}}}title")
        if title is not None:
            heading = E("p", {"data-type": "list-title"})
            self.copy_id(title, heading)
            self.inline_children(title, heading)
            dst.append(heading)
            heading.tail = None
        if inline:
            out = E("span", {"data-type": "list", "data-display": "inline",
                             "class": el.get("class")})
            self.copy_id(el, out)
            # An inline list's items in a run, each after the separator
            # CNXML gives it (";" by default), an enumerated one's after
            # its mark ("a."), as cnx.org showed them. OpenStax's assembly
            # writes neither, and their stylesheet adds what it shows.
            sep = el.get("item-sep", ";")
            start = el.get("start-value", "1")
            start = int(start) if start.strip().isdigit() else 1
            items = el.findall(f"{{{CNXML}}}item")
            for i, item in enumerate(items):
                if i:
                    append_text(out, sep if sep.endswith(" ") else sep + " ")
                span = E("span", {"data-type": "item"})
                self.copy_id(item, span)
                if list_type == "enumerated":
                    span.text = (el.get("mark-prefix", "")
                                 + list_mark(start + i,
                                             el.get("number-style"))
                                 + el.get("mark-suffix", ".") + " ")
                self.item_content(item, span)
                out.append(span)
            dst.append(out)
            return
        tag = "ol" if list_type == "enumerated" else "ul"
        if "circled" in (el.get("class") or "").split():
            # Its items open with their circled letters ("ⓐ"), and
            # OpenStax's stylesheet hides the list's own numbers, which a
            # converted book can't: numbered, an item would read "1. ⓐ".
            tag = "ul"
        out = E(tag, {"class": el.get("class")})
