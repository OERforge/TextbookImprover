    def do_media(self, el, dst):
        out = E("span", {"data-type": "media", "class": el.get("class")})
        self.copy_id(el, out)
        # Composed (NFC), as HTML wants an attribute's text: a hat typed
        # as a letter and a combining accent is one character.
        alt = unicodedata.normalize("NFC", el.get("alt", ""))
        out.set("data-alt", alt)
        if el.get("display"):
            out.set("data-display", el.get("display"))
        if el.get("longdesc"):
            out.set("data-longdesc", el.get("longdesc"))
        chosen = self.choose_media(el)
        for child in chosen:
            name = local(child)
            if name == "image":
                src = self.book.media_href(self.module, child.get("src", ""))
                if src in getattr(self.book, "missing_media", {}):
                    # A picture the repository doesn't have: its
                    # description where it would stand, since a page
                    # naming a file that isn't there stops convert.py.
                    gone = E("span", {"data-type": "missing-media"})
                    gone.text = f"[{alt or 'A picture'}: missing]"
                    out.append(gone)
                    continue
                img = E("img", {"src": src, "alt": alt})
                if child.get("width"):
                    img.set("width", child.get("width"))
                if child.get("height"):
                    img.set("height", child.get("height"))
                if child.get("class"):
                    img.set("class", child.get("class"))
                img.set("data-media-type", child.get("mime-type", ""))
                out.append(img)
            elif name == "iframe":
                out.append(self.frame(child, alt))
            elif name in ("video", "audio"):
                tag = name
                media = E(tag, {"src": self.book.media_href(
                    self.module, child.get("src", "")), "controls": "controls"})
                if alt:
                    media.text = alt
                out.append(media)
            elif name == "download":
                link = E("a", {"href": self.book.media_href(
                    self.module, child.get("src", "")),
                    "data-type": "download"})
                link.text = alt or posixpath.basename(child.get("src", ""))
                out.append(link)
            else:
                # Flash, LabVIEW, a Java applet, an <object>: nothing can
                # play these now. A link to the file, if it's here.
                src = child.get("src") or child.get("url") or ""
                link = E("a", {"data-type": "obsolete-media",
                               "class": name})
                if src:
                    link.set("href", self.book.media_href(self.module, src))
                link.text = alt or f"[{name}]"
                out.append(link)
                self.note("obsolete-media", f"<{name}> {src}: a link now")
        if not len(out):
            self.note("media-with-nothing-to-show", etree.tostring(
                el, encoding="unicode", with_tail=False)[:200])
        dst.append(out)

    def choose_media(self, el):
        """The children to show. An image for="pdf" is print's; one
        for="online" or for="default" (or with no for) is the web's."""
        kids = [c for c in el if isinstance(c.tag, str) and
                ns(c) == CNXML and local(c) != "param"]
        online = [c for c in kids if c.get("for", "default") != "pdf"]
        return online or kids[:1]

